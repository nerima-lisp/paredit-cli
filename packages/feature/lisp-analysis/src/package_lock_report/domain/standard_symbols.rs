/// Whether `name` is a symbol this table knows to live in `COMMON-LISP`.
///
/// `name` must already be reader-folded — upper-cased, with any `#:`/`:`
/// designator prefix and `|…|` escapes removed. Folding here instead would
/// hide the fact that the caller has a designator rather than a symbol.
#[must_use]
pub fn is_standard_symbol(name: &str) -> bool {
    STANDARD_SYMBOLS.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_so_the_binary_search_is_valid() {
        let mut sorted = STANDARD_SYMBOLS;
        sorted.sort_unstable();
        assert_eq!(sorted, STANDARD_SYMBOLS, "the table must stay sorted");
    }

    #[test]
    fn the_table_holds_no_duplicate() {
        let mut sorted = STANDARD_SYMBOLS.to_vec();
        sorted.sort_unstable();
        let count = sorted.len();
        sorted.dedup();
        assert_eq!(sorted.len(), count);
    }

    #[test]
    fn common_operators_and_accessors_are_present() {
        for name in ["LIST", "CAR", "WHEN", "FORMAT", "T", "NIL", "LENGTH"] {
            assert!(is_standard_symbol(name), "{name}");
        }
    }

    #[test]
    fn an_application_name_is_absent() {
        for name in ["RENDER-PANE", "MY-LIST", "APP"] {
            assert!(!is_standard_symbol(name), "{name}");
        }
    }

    #[test]
    fn lookup_expects_a_folded_name() {
        assert!(is_standard_symbol("LIST"));
        assert!(!is_standard_symbol("list"));
    }
}
