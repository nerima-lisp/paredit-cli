//! The JSON Schema for the `inspect capabilities` document.
//!
//! The catalog is this tool's machine-readable interface: an agent reads it to
//! learn every command, flag, default, and enum value without a failed
//! invocation per discovery. Publishing a schema for it is what turns that from
//! "a JSON blob you can pattern-match" into something a consumer can generate
//! types from and validate against.
//!
//! Written by hand rather than derived. The catalog is not a Rust type — it is
//! assembled from clap's own command tree — so there is nothing to derive from,
//! and a hand-written schema is anyway the only one that can carry the
//! *meaning* of a field: that `possible_values` absent means the option is not
//! an enum, that `silent` means a command ran and knew nothing.
//!
//! The version parameter matters: schema version 1 has no `dialect_contract`,
//! 2 adds it without tiers, 3 adds tiers and the `silent` status. A single
//! permissive schema covering all three would validate a version 1 document
//! carrying a version 3 field, which is exactly the drift the catalog's
//! version number exists to catch.
//!
//! `command.writes` and `command.possible_error_codes` are the one
//! deliberate exception to that discipline: both are populated on every
//! command regardless of `schema_version`, and their `$defs` entry (in
//! [`definitions`]) is not gated behind a `version >= N` check the way
//! `dialectContract` is. That is safe rather than an oversight, because the
//! two things a version number has to protect against don't apply to them:
//! they are additive-only leaf properties on a node that already exists in
//! every version (unlike `dialect_contract`, which changes the *shape* of
//! the document by adding a whole new top-level collection), and no version
//! ever populated the catalog without them, so there is no older document
//! shape a schema revision could be asked to keep validating. Widening a
//! schema in place is exactly the drift this module otherwise refuses to
//! allow — the fields are exempted here, not the discipline.
//! `cli_capabilities_schema_pins_writes_and_error_codes_as_intentionally_unversioned`
//! in `tests/cli/capabilities_schema.rs` pins this as a tested contract
//! rather than a comment that can go stale.

use serde_json::{Value, json};

/// The published schema identifier, versioned alongside the catalog.
fn schema_id(version: u8) -> String {
    format!("https://nerima-lisp.github.io/paredit-cli/schema/capabilities-v{version}.json")
}

/// Builds the JSON Schema (draft 2020-12) for a capabilities document at
/// `version`.
pub(super) fn capabilities_schema(version: u8) -> Value {
    let mut root = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": schema_id(version),
        "title": format!("paredit inspect capabilities, schema version {version}"),
        "description":
            "The machine-readable catalog of every paredit command, flag, default, and \
             enum value, generated by walking the argument parser's own command tree.",
        "type": "object",
        "required": ["schema_version", "name", "commands"],
        "additionalProperties": false,
        "properties": {
            "schema_version": {
                "const": version,
                "description":
                    "The catalog's own version. A consumer should validate against the \
                     schema matching this number rather than the newest one.",
            },
            "name": { "type": "string", "const": "paredit" },
            "version": {
                "type": ["string", "null"],
                "description": "The paredit release that produced this catalog.",
            },
            "about": { "type": ["string", "null"] },
            "commands": {
                "type": "array",
                "items": { "$ref": "#/$defs/command" },
            },
        },
        "$defs": definitions(version),
    });

    if version >= 2 {
        root["required"]
            .as_array_mut()
            .expect("required array")
            .push(json!("dialect_contract"));
        root["properties"]["dialect_contract"] = json!({ "$ref": "#/$defs/dialectContract" });
    }

    root
}

