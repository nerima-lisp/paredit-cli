/// The status vocabulary a schema version can express.
///
/// `silent` — the command ran, exited zero, and knew nothing about the file's
/// dialect — is the distinction version 3 added. Earlier versions fold it onto
/// `unsupported`, so their schemas must not admit the word.
fn status_values(version: u8) -> Value {
    if version >= 3 {
        json!(["supported", "silent", "unsupported", "unknown"])
    } else {
        json!(["supported", "unsupported", "unknown"])
    }
}

fn dialect_contract_schema(version: u8) -> Value {
    let statuses = status_values(version);

    let mut schema = json!({
        "type": "object",
        "description":
            "How far each command's analysis reaches into each dialect. This tool \
             parses ten dialects and models far fewer of them semantically; the \
             contract is what separates 'found nothing' from 'looked for nothing'.",
        "required": [
            "command_count", "dialect_count", "cell_count",
            "categories", "statuses", "dialects", "commands",
        ],
        "additionalProperties": false,
        "properties": {
            "command_count": { "type": "integer", "minimum": 0 },
            "dialect_count": { "type": "integer", "minimum": 0 },
            "cell_count": {
                "type": "integer",
                "minimum": 0,
                "description": "command_count × dialect_count, the size of the matrix.",
            },
            "categories": {
                "type": "array",
                "items": { "enum": ["introspection", "format", "structural", "semantic"] },
            },
            "statuses": { "type": "array", "items": { "enum": statuses } },
            "dialects": { "type": "array", "items": { "type": "string" } },
            "commands": { "type": "array", "items": { "$ref": "#/$defs/commandSupport" } },
        },
    });

    if version >= 3 {
        for key in ["tiers", "semantic_layers", "dialect_depth"] {
            schema["required"]
                .as_array_mut()
                .expect("required array")
                .push(json!(key));
        }
        schema["properties"]["tiers"] = json!({
            "type": "array",
            "items": { "enum": ["syntax", "scope", "common-lisp-family", "common-lisp-semantics"] },
            "description":
                "What a command needs from a dialect before its analysis means \
                 anything, from the balanced-parens tree up to the Common Lisp \
                 package and operator model.",
        });
        schema["properties"]["semantic_layers"] = json!({
            "type": "array",
            "items": { "enum": semantic_layer_values() },
            "description":
                "The semantic layers the `common-lisp-semantics` tier's six \
                 introspection commands (types, narrowing, constants, \
                 value-propagation, effects, semantic-coverage) are actually \
                 built from. Each names the field a command with that layer \
                 carries in `commands[].layer`.",
        });
        schema["properties"]["dialect_depth"] = json!({
            "type": "array",
            "description":
                "Per dialect, how many commands land in each status — the answer to \
                 'how deep does this tool go for my dialect' in one read.",
            "items": {
                "type": "object",
                "required": [
                    "dialect", "family", "separates_function_namespace",
                    "by_status", "verified_semantic_operations",
                ],
                "additionalProperties": false,
                "properties": {
                    "dialect": { "type": "string" },
                    "family": {
                        "type": "string",
                        "description": "The dialect's own name for itself, spelled as its \
                                        community spells it.",
                    },
                    "separates_function_namespace": {
                        "type": "boolean",
                        "description":
                            "Whether the dialect is a Lisp-2. It decides whether a rename \
                             of a variable can collide with a function of the same name.",
                    },
                    "by_status": {
                        "type": "object",
                        "description": "How many commands land in each status for this dialect.",
                        "additionalProperties": { "type": "integer", "minimum": 0 },
                    },
                    "verified_semantic_operations": {
                        "type": "array",
                        "items": { "type": "string" },
                        "description":
                            "The scope-level operations this dialect is tested against, \
                             as opposed to merely parsed for.",
                    },
                },
            },
        });
    }

    schema
}

fn command_support_schema(version: u8) -> Value {
    let statuses = status_values(version);
    let mut schema = json!({
        "type": "object",
        "required": ["path", "category", "support"],
        "additionalProperties": false,
        "properties": {
            "path": {
                "type": "string",
                "description": "The command's space-separated path, e.g. `inspect lint`.",
            },
            "category": {
                "enum": ["introspection", "format", "structural", "semantic"],
            },
            "support": {
                "type": "object",
                "description": "One status per dialect, keyed by the dialect's name.",
                "additionalProperties": { "enum": statuses },
            },
        },
    });

    if version >= 3 {
        schema["required"]
            .as_array_mut()
            .expect("required array")
            .push(json!("tier"));
        schema["properties"]["tier"] = json!({
            "enum": ["syntax", "scope", "common-lisp-family", "common-lisp-semantics"],
        });
        // Optional, not required: only the six `common-lisp-semantics`-tier
        // introspection commands (types, narrowing, constants,
        // value-propagation, effects, semantic-coverage) carry a layer. Every
        // other command's dialect support is fully named by its tier alone.
        schema["properties"]["layer"] = json!({
            "enum": semantic_layer_values(),
            "description":
                "Which semantic layer actually decided this command's dialect \
                 support, for the commands whose tier is \
                 `common-lisp-semantics`. Absent for every other command.",
        });
    }

    schema
}

fn semantic_layer_values() -> Value {
    json!([
        "typing",
        "narrowing",
        "constants",
        "value-propagation",
        "effects",
        "semantic-coverage",
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_schema_pins_the_version_it_describes() {
        for version in 1..=3 {
            let schema = capabilities_schema(version);
            assert_eq!(schema["properties"]["schema_version"]["const"], version);
            assert!(
                schema["$id"]
                    .as_str()
                    .is_some_and(|id| id.ends_with(&format!("capabilities-v{version}.json"))),
                "version {version} must publish under its own id"
            );
        }
    }

    /// Version 1 has no dialect contract, so its schema must not admit one.
    ///
    /// A single permissive schema would validate a version 1 document carrying
    /// a version 3 field, which is the drift the version number exists to
    /// catch.
    #[test]
    fn version_one_rejects_the_dialect_contract_it_does_not_carry() {
        let schema = capabilities_schema(1);
        assert_eq!(schema["additionalProperties"], false);
        assert!(schema["properties"]["dialect_contract"].is_null());
        assert!(schema["$defs"]["dialectContract"].is_null());
    }

    #[test]
    fn the_silent_status_and_tiers_appear_only_from_version_three() {
        let statuses = |version| {
            capabilities_schema(version)["$defs"]["dialectContract"]["properties"]["statuses"]
                ["items"]["enum"]
                .clone()
        };
        assert_eq!(statuses(2), json!(["supported", "unsupported", "unknown"]));
        assert_eq!(
            statuses(3),
            json!(["supported", "silent", "unsupported", "unknown"])
        );
        assert!(
            capabilities_schema(2)["$defs"]["dialectContract"]["properties"]["tiers"].is_null()
        );
    }
}
